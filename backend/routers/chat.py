@router.post("/send", response_model=dict)
async def send_message(
    chat_request: ChatRequest,
    db: AsyncSession = Depends(get_db)
):
    """
    ????? ????? ?????? ???????
    Send message to AI
    """
    # ?????? ??? ?????? ?? ????? ?????
    session = None
    
    if chat_request.session_id:
        result = await db.execute(
            select(ChatSession).where(
                ChatSession.session_id == chat_request.session_id,
                ChatSession.is_active == True
            )
        )
        session = result.scalar_one_or_none()
    
    if not session:
        # ????? ???? ?????
        session = ChatSession(
            session_id=chat_request.session_id or str(uuid.uuid4()),
            device_id=chat_request.device_id,
            is_hotspot=chat_request.is_hotspot,
            context={}
        )
        db.add(session)
        await db.commit()
        await db.refresh(session)
    
    # ??? ????? ????????
    user_message = ChatMessage(
        session_id=session.id,
        role="user",
        content=chat_request.message
    )
    db.add(user_message)
    await db.commit()
    
    # ????? ?????
    context = session.context or {}
    
    if chat_request.device_id:
        # ?????? ??? ??????? ?????? ??????
        device_result = await db.execute(
            select(Device).where(Device.id == chat_request.device_id)
        )
        device = device_result.scalar_one_or_none()
        
        if device:
            context['device'] = {
                "id": device.id,
                "name": device.name,
                "ip_address": device.ip_address,
                "model": device.model,
                "status": device.status.value
            }
    
    intent_analysis = await ai_brain.analyze_intent(
        user_message=chat_request.message,
        context=context
    )
    
    # ????? ???? ????? ??? ?????
    response_content = await _generate_response(
        intent_analysis,
        chat_request.message,
        context,
        db
    )
    
    # ??? ?? ?????? ???????
    ai_message = ChatMessage(
        session_id=session.id,
        role="assistant",
        content=response_content,
        ai_model=ai_brain.openai_model,
        intent=intent_analysis.get('intent'),
        confidence=intent_analysis.get('confidence'),
        metadata=intent_analysis
    )
    db.add(ai_message)
    
    # ????? ???? ??????
    session.context = context
    
    await db.commit()
    
    return {
        "session_id": session.session_id,
        "message": response_content,
        "intent": intent_analysis,
        "timestamp": datetime.now().isoformat()
    }

@router.get("/sessions", response_model=List[ChatSessionResponse])
async def list_chat_sessions(
    active_only: bool = True,
    limit: int = 50,
    db: AsyncSession = Depends(get_db)
):
    """
    ????? ????? ????????
    List chat sessions
    """
    query = select(ChatSession)
    
    if active_only:
        query = query.where(ChatSession.is_active == True)
    
    query = query.order_by(ChatSession.started_at.desc()).limit(limit)
    
    result = await db.execute(query)
    sessions = result.scalars().all()
    
    return sessions

@router.get("/sessions/{session_id}/messages", response_model=List[ChatMessageResponse])
async def get_session_messages(
    session_id: str,
    db: AsyncSession = Depends(get_db)
):
    """
    ?????? ??? ????? ???? ?????
    Get session messages
    """
    # ?????? ??? ??????
    session_result = await db.execute(
        select(ChatSession).where(ChatSession.session_id == session_id)
    )
    session = session_result.scalar_one_or_none()
    
    if not session:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Session {session_id} not found"
        )
    
    # ?????? ??? ???????
    messages_result = await db.execute(
        select(ChatMessage)
        .where(ChatMessage.session_id == session.id)
        .order_by(ChatMessage.created_at.asc())
    )
    messages = messages_result.scalars().all()
    
    return messages

@router.post("/sessions/{session_id}/end")
async def end_chat_session(
    session_id: str,
    db: AsyncSession = Depends(get_db)
):
    """
    ????? ???? ??????
    End chat session
    """
    result = await db.execute(
        select(ChatSession).where(ChatSession.session_id == session_id)
    )
    session = result.scalar_one_or_none()
    
    if not session:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Session {session_id} not found"
        )
    
    session.is_active = False
    session.ended_at = datetime.now()
    
    await db.commit()
    
    return {"message": "Session ended successfully"}

@router.post("/analyze-command")
async def analyze_command(
    command: str = Field(..., min_length=1),
    device_id: int | None = None,
    db: AsyncSession = Depends(get_db)
):
    """
    ????? ??? RouterOS
    Analyze RouterOS command
    """
    device_info = {}
    
    if device_id:
        device_result = await db.execute(
            select(Device).where(Device.id == device_id)
        )
        device = device_result.scalar_one_or_none()
        
        if device:
            device_info = {
                "model": device.model,
                "routeros_version": device.routeros_version,
                "ip_address": device.ip_address
            }
    
    # ????? ????? RouterOS
    script_result = await ai_brain.generate_routeros_script(
        task_description=command,
        device_info=device_info
    )
    
    return script_result

